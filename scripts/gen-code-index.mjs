#!/usr/bin/env node
// Generates docs/93-code-index.md: every source file with its purpose (first doc comment) and exports,
// the routes, the i18n namespaces and the tests per folder. Read docs/92-code-map.md first, use this
// index to find the right file quickly.
//
//   npm run map            regenerate
//   node scripts/gen-code-index.mjs --check    exit 1 if the file is stale (no writing)
//
// `npm run check` regenerates it automatically.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, extname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { pkg, ROOT } from './lib.mjs';

const OUT = 'docs/93-code-index.md';

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(path));
    else out.push(path);
  }
  return out;
}

const isTest = (file) => /\.test\.tsx?$/.test(file);
const isSource = (file) => /\.tsx?$/.test(file) && !isTest(file);
const clean = (comment) =>
  comment
    .split('\n')
    .map((l) => l.replace(/^\s*\*+\s?/, '').trim())
    .filter(Boolean)
    .join(' ')
    .replace(/\s+/g, ' ');

/** First sentence of a comment: ends at ". " (not after e.g./i.e.) – colons and dashes stay in. */
function firstSentence(comment) {
  const c = clean(comment);
  const end = c.search(/(?<!\be\.g)(?<!\bi\.e)(?<!\betc)[.!?](\s|$)/);
  const sentence = end >= 0 ? c.slice(0, end + 1) : c;
  return (sentence.length > 150 ? `${sentence.slice(0, 147)}…` : sentence).replace(/\|/g, '\\|');
}

const usable = (comment) => {
  const c = clean(comment);
  return c.length >= 8 && !/^(eslint|@ts-|@vitest|global \w+(, \w+)*$)/i.test(c);
};

/**
 * What the file is for, in order of preference: the header comment at the top of the file, the doc
 * comment above the first exported function/const/class, then any block comment.
 */
function purpose(text) {
  const header = text.match(/^\s*(?:\/\/[^\n]*\n\s*)*\/\*\*?((?:(?!\*\/)[\s\S])*)\*\//);
  if (header && usable(header[1])) return firstSentence(header[1]);
  const above = text.match(/\/\*\*((?:(?!\*\/)[\s\S])*)\*\/\s*export\s+(?:default\s+)?(?:async\s+)?(?:function|const|class)\b/);
  if (above && usable(above[1])) return firstSentence(above[1]);
  for (const m of text.matchAll(/\/\*\*?((?:(?!\*\/)[\s\S])*)\*\//g)) if (usable(m[1])) return firstSentence(m[1]);
  return '';
}

function exportsOf(text) {
  const values = [];
  const types = [];
  for (const m of text.matchAll(/^export\s+(?:default\s+)?(?:async\s+)?(function\*?|const|let|class|interface|type|enum)\s+(\w+)/gm)) {
    (m[1] === 'interface' || m[1] === 'type' ? types : values).push(m[2]);
  }
  for (const m of text.matchAll(/^export\s*\{([^}]+)\}/gm)) {
    for (const name of m[1].split(',')) {
      const n = name.trim().split(/\s+as\s+/).pop()?.replace(/^type\s+/, '');
      if (n) values.push(n);
    }
  }
  const cut = (list, max) => (list.length > max ? `${list.slice(0, max).join(', ')}, …` : list.join(', '));
  const parts = [cut(values, 8)];
  if (types.length) parts.push(`types: ${cut(types, 4)}`);
  return parts.filter(Boolean).join(' · ').replace(/\|/g, '\\|');
}

function routes() {
  const rows = [];
  const files = walk(join(ROOT, 'src/features')).filter((f) => /\/index\.ts$/.test(f)).concat(join(ROOT, 'src/app/routes.tsx'));
  for (const file of files) {
    const text = readFileSync(file, 'utf8');
    const rel = relative(ROOT, file);
    for (const m of text.matchAll(/path:\s*'(\/[^']*)'[^}]*?createElement\((\w+)\)/g)) rows.push([m[1], m[2], rel]);
    for (const m of text.matchAll(/path:\s*'(\/[^']*)'[^\n]*element:\s*<(\w+)/g)) rows.push([m[1], m[2], rel]);
  }
  const seen = new Set();
  return rows
    .filter(([p, c]) => !seen.has(`${p}|${c}`) && seen.add(`${p}|${c}`))
    .sort((a, b) => a[0].localeCompare(b[0], 'en'));
}

function namespaces() {
  const dir = join(ROOT, 'src/locales/de');
  const count = (v) => (v && typeof v === 'object' ? Object.values(v).reduce((n, x) => n + count(x), 0) : 1);
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((f) => [basename(f, '.json'), count(JSON.parse(readFileSync(join(dir, f), 'utf8')))]);
}

function build() {
  const files = walk(join(ROOT, 'src')).filter((f) => /\.tsx?$/.test(f));
  const byDir = new Map();
  for (const file of files) {
    const dir = relative(ROOT, dirname(file));
    if (!byDir.has(dir)) byDir.set(dir, { sources: [], tests: [] });
    (isTest(file) ? byDir.get(dir).tests : byDir.get(dir).sources).push(file);
  }

  const lines = [
    '# Code index (generated)',
    '',
    `> Generated by \`scripts/gen-code-index.mjs\` for version ${pkg().version} – **do not edit by hand** (\`npm run map\`, also part of \`npm run check\`).`,
    '> Start with [`92-code-map.md`](92-code-map.md) (concepts, data layout, recipes); use this index to find the file.',
    '',
    '## Routes',
    '',
    '| Path | Screen | Registered in |',
    '|---|---|---|',
    ...routes().map(([p, c, f]) => `| \`${p}\` | ${c} | \`${f}\` |`),
    '',
    '## Texts (German, `src/locales/de/<namespace>.json`)',
    '',
    namespaces().map(([n, c]) => `\`${n}\` (${c})`).join(' · '),
    '',
    '## Source files by folder',
  ];

  for (const [dir, { sources, tests }] of [...byDir].sort((a, b) => a[0].localeCompare(b[0], 'en'))) {
    lines.push('', `### \`${dir}\``, '');
    if (sources.length) {
      lines.push('| File | Purpose | Exports |', '|---|---|---|');
      for (const file of sources.sort()) {
        const text = readFileSync(file, 'utf8');
        lines.push(`| \`${basename(file)}\` | ${purpose(text)} | ${exportsOf(text)} |`);
      }
    }
    if (tests.length) {
      const list = tests
        .sort()
        .map((f) => `${basename(f)} (${(readFileSync(f, 'utf8').match(/^\s*it\(/gm) ?? []).length})`)
        .join(', ');
      lines.push('', `Tests: ${list}`);
    }
  }
  return `${lines.join('\n')}\n`;
}

/** Regenerates the file. Returns a short status message; with `write: false` only compares. */
export function generateIndex({ write = true } = {}) {
  const next = build();
  let current = '';
  try {
    current = readFileSync(join(ROOT, OUT), 'utf8');
  } catch {
    // first run
  }
  if (current === next) return `${OUT} up to date`;
  if (write) writeFileSync(join(ROOT, OUT), next);
  return write ? `${OUT} updated` : `${OUT} is STALE – run npm run map`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const message = generateIndex({ write: !check });
  console.log(message);
  process.exit(check && message.includes('STALE') ? 1 : 0);
}
